import { NextResponse } from "next/server";

// Изображения каталога скачиваются фоновой синхронизацией и раздаются с нашего
// диска. Старый публичный прокси отключён, чтобы произвольный запрос посетителя
// или бота не мог инициировать обращение к API МойСклад.
export async function GET() {
  return NextResponse.json(
    { error: "Изображения МойСклад доступны только из локального зеркала каталога" },
    { status: 410 }
  );
}
